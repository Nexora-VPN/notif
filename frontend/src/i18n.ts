export const locales = [
  { code: 'fa', name: 'فارسی', rtl: true },
  { code: 'en', name: 'English', rtl: false },
  { code: 'ru', name: 'Русский', rtl: false },
  { code: 'zh', name: '中文', rtl: false },
] as const

export type Locale = (typeof locales)[number]['code']

function initial(): Locale {
  try {
    const saved = localStorage.getItem('notif.locale')
    if (locales.some((l) => l.code === saved)) return saved as Locale
  } catch {
    // storage blocked
  }
  const nav = navigator.language.slice(0, 2)
  return (locales.find((l) => l.code === nav)?.code ?? 'en') as Locale
}

export const i18n = createI18n({
  legacy: false,
  locale: initial(),
  fallbackLocale: 'en',
  messages: { en, fa, ru, zh },
})

// fieldText is a channel field's words: the kind's own, else the ones the
// kinds share (fields.*), else fallback.
export function fieldText(kind: string, key: string, fallback: string) {
  const { t, te } = i18n.global
  if (te('kinds.' + kind + '.' + key)) return t('kinds.' + kind + '.' + key)
  if (te('fields.' + key)) return t('fields.' + key)
  return fallback
}

// fieldLabel is a channel field's label, as the channel form shows it.
export function fieldLabel(kind: string, key: string) {
  return fieldText(kind, key, key)
}

export function setLocale(code: Locale) {
  i18n.global.locale.value = code
  try {
    localStorage.setItem('notif.locale', code)
  } catch {
    // storage blocked
  }
  applyDirection()
}

export function applyDirection() {
  const l = locales.find((x) => x.code === i18n.global.locale.value)
  document.documentElement.lang = l?.code ?? 'en'
  document.documentElement.dir = l?.rtl ? 'rtl' : 'ltr'
}

