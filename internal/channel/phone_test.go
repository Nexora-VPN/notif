package channel

import "testing"

func TestPhones(t *testing.T) {
	cases := []struct{ in, e164, iran string }{
		{"+98 912 000 0001", "+989120000001", "09120000001"},
		{"09120000001", "+989120000001", "09120000001"},
		{"۰۹۱۲۰۰۰۰۰۰۱", "+989120000001", "09120000001"},
		{"9120000001", "+989120000001", "09120000001"},
		{"0098 912 000 0001", "+989120000001", "09120000001"},
		{"+7 (912) 345-67-89", "+79123456789", ""},
		{"8 912 345 67 89", "+79123456789", ""},
		{"+86 138 0013 8000", "+8613800138000", ""},
		{"call me", "", ""},
		{"123", "", ""},
	}
	for _, c := range cases {
		if got := E164(c.in); got != c.e164 {
			t.Errorf("E164(%q) = %q, want %q", c.in, got, c.e164)
		}
		if got := IranLocal(c.in); got != c.iran {
			t.Errorf("IranLocal(%q) = %q, want %q", c.in, got, c.iran)
		}
	}
}
